const OpcodeName* OpcodeName::find(std::uint8_t opcode) noexcept {
    if (opcode >= 256) {
        return nullptr;
    }
    return &gNames[static_cast<std::size_t>(opcode)];
}

const OpcodeName* OpcodeName::byName(const char* name) noexcept {
    for (const auto& entry : gNames) {
        if (entry.name_ == name || (entry.aliases_.empty() == false &&
                                     entry.aliases_.find(name) != std::string::npos)) {
            return &entry;
        }
    }
    return nullptr;
}

const std::vector<OpcodeName> OpcodeName::all() noexcept {
    std::vector<OpcodeName> result;
    result.reserve(gNames.size());
    for (const auto& entry : gNames) {
        result.push_back(entry);
    }
    return result;
}

const std::vector<OpcodeName> OpcodeName::byMnemonic(const char* mnemonic) noexcept {
    std::vector<OpcodeName> result;
    for (const auto& entry : gNames) {
        if (entry.mnemonic_ == mnemonic) {
            result.push_back(entry);
        }
    }
    return result;
}

const std::vector<OpcodeName> OpcodeName::byFormat(const char* format) noexcept {
    std::vector<OpcodeName> result;
    for (const auto& entry : gNames) {
        if (entry.format_ == format) {
            result.push_back(entry);
        }
    }
    return result;
}

